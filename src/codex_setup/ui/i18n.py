_TABLES: dict[str, dict[str, str]] = {"en": EN, "vi": VI}


def default_lang(env: Mapping[str, str] | None = None) -> str:
    e = os.environ if env is None else env
    forced = (e.get("CODEX_SETUP_LANG") or "").strip().lower()
    if forced in _TABLES:
        return forced
    for key in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = (e.get(key) or "").lower()
        if value:
            return "vi" if value.startswith("vi") else "en"
    try:
        loc = (locale.getlocale()[0] or "").lower()
    except (ValueError, TypeError):
        loc = ""
    return "vi" if loc.startswith("vi") else "en"


def set_lang(lang: str) -> None:
    global _LANG
    _LANG = lang if lang in _TABLES else "en"


def get_lang() -> str:
    return _LANG


def t(key: str, **kw: object) -> str:
    text = _TABLES[_LANG].get(key) or EN.get(key) or key
    return text.format(**kw) if kw else text


def tr_step(step: object) -> str:
    """Localized detail of an api_test StepResult (falls back to the English detail)."""
    code = getattr(step, "code", None)
    if code and (code in EN):
        try:
            return t(code, **getattr(step, "params", {}))
        except (KeyError, IndexError):
            pass
    return str(getattr(step, "detail", ""))


def tr_check(check: object) -> tuple[str, str, str]:
    """Localized (title, detail, fix) of a diagnostics CheckResult."""
    code = getattr(check, "code", "") or ""
    params = dict(getattr(check, "params", {}) or {})

    def pick(key: str, fallback: str) -> str:
        if key in EN:
            try:
                return t(key, **params)
            except (KeyError, IndexError):
                pass
        return fallback

    return (
        pick(code, getattr(check, "title", "")),
        pick(code + "_d", getattr(check, "detail", "")),
        pick(code + "_f", getattr(check, "fix", "")),
    )
